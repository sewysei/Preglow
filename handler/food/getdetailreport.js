import { PDFDocument, rgb, StandardFonts } from "pdf-lib";
import checkToken, { isBlacklisted } from "../../middleware/auth.js";
import Food from "../../models/Food.js";

export const getDetailReport = async (req, res) => {
  try {
    // --- Token check ---
    const authHeader = req.headers.authorization;
    if (!authHeader || !authHeader.startsWith("Bearer ")) {
      return res.status(401).json({ message: "No token provided." });
    }

    const token = authHeader.split(" ")[1];
    const { valid, expired, decoded } = checkToken(token);
    const userId = decoded?.id;

    if (!valid)
      return res
        .status(401)
        .json({ message: expired ? "Token expired." : "Invalid token." });
    if (await isBlacklisted(token))
      return res.status(401).json({ message: "Token has been invalidated." });
    if (!userId)
      return res
        .status(401)
        .json({ message: "Unauthorized: missing user ID." });

    // --- Ambil data hari ini ---
    const startOfDay = new Date();
    startOfDay.setHours(0, 0, 0, 0);
    const endOfDay = new Date();
    endOfDay.setHours(23, 59, 59, 999);

    const foods = await Food.find({
      userId,
      createdAt: { $gte: startOfDay, $lte: endOfDay },
    }).sort({ createdAt: 1 });

    // --- Buat PDF ---
    const pdfDoc = await PDFDocument.create();
    const helvetica = await pdfDoc.embedFont(StandardFonts.Helvetica);
    const helveticaBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

    let page = pdfDoc.addPage([600, 800]);
    const { width, height } = page.getSize();

    // === HEADER ===
    page.drawRectangle({
      x: 0,
      y: height - 80,
      width,
      height: 80,
      color: rgb(0.2, 0.3, 0.6),
    });

    page.drawText("Daily Food Report", {
      x: 50,
      y: height - 50,
      size: 24,
      font: helveticaBold,
      color: rgb(1, 1, 1),
    });

    const today = new Date().toLocaleDateString("id-ID", {
      weekday: "long",
      year: "numeric",
      month: "long",
      day: "numeric",
    });
    page.drawText(`Tanggal: ${today}`, {
      x: 400,
      y: height - 60,
      size: 10,
      font: helvetica,
      color: rgb(1, 1, 1),
    });

    // === BODY ===
    let y = height - 120;

    if (foods.length === 0) {
      page.drawText("Tidak ada data makanan untuk hari ini.", {
        x: 50,
        y,
        size: 14,
        font: helvetica,
        color: rgb(0.2, 0.2, 0.2),
      });
    } else {
      // Header kolom
      page.drawText("Kategori", { x: 50, y, size: 12, font: helveticaBold });
      page.drawText("Nama", { x: 150, y, size: 12, font: helveticaBold });
      page.drawText("Kalori", { x: 320, y, size: 12, font: helveticaBold });
      page.drawText("Protein", { x: 390, y, size: 12, font: helveticaBold });
      page.drawText("Karbo", { x: 470, y, size: 12, font: helveticaBold });
      page.drawText("Lemak", { x: 540, y, size: 12, font: helveticaBold });

      y -= 10;
      page.drawLine({
        start: { x: 50, y },
        end: { x: 560, y },
        thickness: 1,
        color: rgb(0.2, 0.3, 0.6),
      });

      y -= 20;
      const lineHeight = 20;

      for (const food of foods) {
        if (y < 60) {
          // Tambah halaman baru
          page = pdfDoc.addPage([600, 800]);
          y = height - 60;
        }

        page.drawText(food.category, { x: 50, y, size: 11, font: helvetica });
        page.drawText(food.name, { x: 150, y, size: 11, font: helvetica });
        page.drawText(`${food.calories}`, {
          x: 320,
          y,
          size: 11,
          font: helvetica,
        });
        page.drawText(`${food.protein}`, {
          x: 390,
          y,
          size: 11,
          font: helvetica,
        });
        page.drawText(`${food.carbs}`, {
          x: 470,
          y,
          size: 11,
          font: helvetica,
        });
        page.drawText(`${food.fat}`, { x: 540, y, size: 11, font: helvetica });

        y -= lineHeight;
      }
    }

    // === FOOTER ===
    const footerText =
      "Generated by PreGlow • " + new Date().toLocaleTimeString("id-ID");
    page.drawRectangle({
      x: 0,
      y: 0,
      width,
      height: 40,
      color: rgb(0.95, 0.95, 0.95),
    });
    page.drawText(footerText, {
      x: 200,
      y: 15,
      size: 10,
      font: helvetica,
      color: rgb(0.3, 0.3, 0.3),
    });

    // === Output ===
    const pdfBytes = await pdfDoc.save();
    res.setHeader("Content-Type", "application/pdf");
    res.setHeader(
      "Content-Disposition",
      "inline; filename=daily-food-report.pdf"
    );
    res.send(Buffer.from(pdfBytes));
  } catch (error) {
    console.error("PDF generation error:", error);
    res.status(500).json({
      status: "Failed",
      message: "Failed to generate PDF report.",
      error: error.message,
    });
  }
};
